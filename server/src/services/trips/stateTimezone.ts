export const isUsState = (s: string) => !!ZONES[s.toUpperCase()];

export function stateTimezone(state?: string | null): string {
  return (state && ZONES[state.toUpperCase()]) || "America/Los_Angeles";
}

/** "2026-11-06T03:15" in [zone] → the real instant. */
export function localToDate(local: string, zone: string): Date {
  const [d, t = "00:00"] = local.split("T");
  const [y, mo, da] = d.split("-").map(Number);
  const [h, mi] = t.split(":").map(Number);
  const asUtc = Date.UTC(y, mo - 1, da, h, mi);
  // The zone's offset at that moment (accounts for daylight saving)
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: zone,
    hourCycle: "h23",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  }).formatToParts(new Date(asUtc));
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value);
  const shown = Date.UTC(get("year"), get("month") - 1, get("day"), get("hour"), get("minute"));
  return new Date(asUtc - (shown - asUtc));
}
